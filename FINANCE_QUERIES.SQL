SELECT CATEGORY, 
       SUM(DEBIT) AS TOTAL_SPENT,
	   ROUND(SUM(DEBIT) * 100.0 / (SELECT SUM (DEBIT) FROM TRANSACTIONS), 1) AS PERCENT_OF_TOTAL
FROM TRANSACTIONS 
WHERE CATEGORY <> 'INCOME'
GROUP BY CATEGORY
ORDER BY TOTAL_SPENT DESC;


